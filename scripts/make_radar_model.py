#!/usr/bin/env python3
"""Build models/radar_mmwave from a radar profile (profiles/*.yaml).

Writes, from the one profile:
  models/radar_mmwave/model.sdf      the Gazebo sensor (ray grid, range, rate)
  models/radar_mmwave/meshes/fov.stl the field-of-view wireframe
  models/radar_mmwave/profile.yaml   a copy of the profile; the tools take
                                     their radar model defaults from it

    ./make_radar_model.py ../profiles/us_d1.yaml
    ./make_radar_model.py ../profiles/iwr6843aop.yaml

Several radars on one vehicle each need their own model, link and topic:

    ./make_radar_model.py ../profiles/us_d1.yaml --name radar_us_d1_left
        -> models/radar_us_d1_left, link radar_link_us_d1_left, topic radar/scan_us_d1_left
"""

import argparse
import math
import os
import shutil

import yaml

from make_fov_mesh import tube_triangles, write_stl
from radar_model import display_angles, fov_segments

HERE = os.path.dirname(os.path.abspath(__file__))
MODEL_DIR = os.path.normpath(os.path.join(HERE, "..", "models", "radar_mmwave"))

SDF = """<?xml version="1.0"?>
<!-- Generated by scripts/make_radar_model.py from {profile}; edit the profile, not this file. -->
<sdf version="1.9">
  <model name="{name}">
    <link name="{link}">
      <inertial>
        <mass>{mass:g}</mass>
        <inertia>
          <ixx>{ixx:.3g}</ixx>
          <ixy>0</ixy>
          <ixz>0</ixz>
          <iyy>{iyy:.3g}</iyy>
          <iyz>0</iyz>
          <izz>{izz:.3g}</izz>
        </inertia>
      </inertial>
      <visual name="visual">
        <geometry>
          <box>
            <size>{sx:g} {sy:g} {sz:g}</size>
          </box>
        </geometry>
        <material>
          <ambient>0.1 0.1 0.1 1</ambient>
          <diffuse>0.1 0.1 0.1 1</diffuse>
        </material>
      </visual>
      <!-- Field-of-view wireframe at {fov_range:g} m. It moves with the link;
           visibility flag 0x2 is masked out of the radar below, so the radar
           does not detect it. -->
      <visual name="fov">
        <cast_shadows>false</cast_shadows>
        <visibility_flags>2</visibility_flags>
        <geometry>
          <mesh>
            <uri>model://{name}/meshes/fov.stl</uri>
          </mesh>
        </geometry>
        <material>
          <ambient>0 0 0 1</ambient>
          <diffuse>0 0 0 1</diffuse>
          <emissive>0.95 0.85 0.25 1</emissive>
        </material>
      </visual>
      <!-- {description}. Gazebo has no radar sensor type: the field of view is
           sampled with a ray grid, and scripts/radar_model.py turns the grid
           into the sparse, noisy detections such a radar reports. -->
      <sensor name="radar" type="gpu_lidar">
        <gz_frame_id>{link}</gz_frame_id>
        <topic>{topic}</topic>
        <ray>
          <scan>
            <horizontal>
              <samples>{az_samples}</samples>
              <resolution>1</resolution>
              <min_angle>{az_min:.6f}</min_angle>
              <max_angle>{az_max:.6f}</max_angle>
            </horizontal>
            <vertical>
              <samples>{el_samples}</samples>
              <resolution>1</resolution>
              <min_angle>{el_min:.6f}</min_angle>
              <max_angle>{el_max:.6f}</max_angle>
            </vertical>
          </scan>
          <!-- Everything but the field-of-view wireframe (flag 0x2). -->
          <visibility_mask>4294967293</visibility_mask>
          <range>
            <min>{range_min:g}</min>
            <max>{range_max:g}</max>
            <resolution>0.01</resolution>
          </range>
        </ray>
        <always_on>1</always_on>
        <update_rate>{rate_hz:g}</update_rate>
        <visualize>true</visualize>
      </sensor>
    </link>
  </model>
</sdf>
"""

CONFIG = """<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>
    Emulated {description} (from {profile}).
    Gazebo has no radar sensor, so the field of view is sampled with a gpu_lidar
    ray grid and reduced to sparse radar detections in scripts/radar_model.py.
  </description>
</model>
"""


def grid(lo_deg, hi_deg, step_deg):
    """(samples, min rad, max rad) of a ray axis; a full circle omits the duplicate end ray."""
    span = hi_deg - lo_deg

    if span >= 360:
        samples = int(round(360 / step_deg))
    else:
        samples = int(round(span / step_deg)) + 1

    return samples, math.radians(lo_deg), math.radians(lo_deg + (samples - 1) * step_deg)


def fov_draw_range(profile):
    """Range at which the field of view is drawn (m), in Gazebo and RViz alike."""
    return float(profile.get("display", {}).get("fov_range", 4.0))


def body(profile):
    """Mass, box size and inertia of the radar unit: a small module unless the profile has a body section."""
    if "body" not in profile:
        return dict(mass=0.05, sx=0.02, sy=0.08, sz=0.06, ixx=2e-5, iyy=2e-5, izz=2e-5)

    mass = profile["body"]["mass"]
    sx, sy, sz = profile["body"]["size"]
    # Solid box.
    return dict(mass=mass, sx=sx, sy=sy, sz=sz, ixx=mass * (sy * sy + sz * sz) / 12.0,
                iyy=mass * (sx * sx + sz * sz) / 12.0, izz=mass * (sx * sx + sy * sy) / 12.0)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("profile", help="profiles/*.yaml")
    p.add_argument("--fov-range", type=float, help="range at which the wireframe is drawn (m); "
                                                    "default: display.fov_range of the profile, else 4")
    p.add_argument("--name", default="radar_mmwave", help="model name; the link and topic derive from it "
                                                          "unless the default name is kept")
    p.add_argument("--rate", type=float, help="scan rate (Hz) instead of the profile's sensor.rate_hz")
    p.add_argument("--out", help="default: models/<name>")
    args = p.parse_args()
    suffix = "" if args.name == "radar_mmwave" else "_" + args.name.removeprefix("radar_")
    args.out = args.out or os.path.join(os.path.dirname(MODEL_DIR), args.name)

    with open(args.profile) as f:
        profile = yaml.safe_load(f)

    s = profile["sensor"]
    fov_range = args.fov_range or fov_draw_range(profile)
    az_samples, az_min, az_max = grid(s["az_min_deg"], s["az_max_deg"], s["az_step_deg"])
    el_samples, el_min, el_max = grid(s["el_min_deg"], s["el_max_deg"], s["el_step_deg"])
    name = os.path.relpath(os.path.abspath(args.profile), os.path.dirname(HERE))
    fields = dict(name=args.name, link="radar_link" + suffix, topic="radar/scan" + suffix, profile=name, description=profile["description"], fov_range=fov_range,
                  az_samples=az_samples, az_min=az_min, az_max=az_max,
                  el_samples=el_samples, el_min=el_min, el_max=el_max,
                  range_min=s["range_min"], range_max=s["range_max"], rate_hz=args.rate or s["rate_hz"],
                  **body(profile))

    os.makedirs(os.path.join(args.out, "meshes"), exist_ok=True)

    with open(os.path.join(args.out, "model.sdf"), "w") as f:
        f.write(SDF.format(**fields))

    with open(os.path.join(args.out, "model.config"), "w") as f:
        f.write(CONFIG.format(**fields))

    # Tubes 2 cm thick at 4 m, thicker further out so they stay visible.
    tris = [t for a, b in fov_segments(fov_range, *display_angles(profile, (az_min, az_max, el_min, el_max)))
            for t in tube_triangles(a, b, 0.005 * fov_range)]
    write_stl(os.path.join(args.out, "meshes", "fov.stl"), tris)

    if os.path.abspath(args.profile) != os.path.abspath(os.path.join(args.out, "profile.yaml")):
        shutil.copyfile(args.profile, os.path.join(args.out, "profile.yaml"))

    print(f"{name}: {az_samples} x {el_samples} rays, {s['range_min']:g}-{s['range_max']:g} m, "
          f"{args.rate or s['rate_hz']:g} Hz -> {os.path.relpath(args.out)}")


if __name__ == "__main__":
    main()
